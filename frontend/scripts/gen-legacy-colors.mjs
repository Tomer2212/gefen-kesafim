// Generates src/legacy-colors.css: Tailwind's palette (oklch) converted to hex, applied only in
// browsers that don't support oklch (Chrome < 111, e.g. Chrome 109 — the last on Windows 7).
// Without it every Tailwind color is dropped there: a white-on-blue button turns white-on-white
// (2026-11-12: a school couldn't see "בחר מועד" on the booking page).
// Re-run after upgrading tailwindcss:  node scripts/gen-legacy-colors.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const theme = readFileSync(join(root, "node_modules/tailwindcss/theme.css"), "utf8");

function oklchToHex(lPct, c, h) {
  const L = lPct / 100;
  const hr = (h * Math.PI) / 180;
  const a = c * Math.cos(hr), b = c * Math.sin(hr);
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = L - 0.0894841775 * a - 1.2914855480 * b;
  const l = l_ ** 3, m = m_ ** 3, s = s_ ** 3;
  const lin = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s,
  ];
  return "#" + lin.map(v => {
    const g = v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055;
    return Math.round(Math.min(1, Math.max(0, g)) * 255).toString(16).padStart(2, "0");
  }).join("");
}

const lines = [];
for (const [, name, l, c, h] of theme.matchAll(/(--color-[a-z]+-\d+):\s*oklch\(([\d.]+)%\s+([\d.]+)\s+([\d.]+)\)/g)) {
  lines.push(`    ${name}: ${oklchToHex(+l, +c, +h)};`);
}
if (lines.length < 200) throw new Error(`only ${lines.length} colors found — theme.css format changed?`);

writeFileSync(join(root, "src/legacy-colors.css"), `/* GENERATED by scripts/gen-legacy-colors.mjs — do not edit by hand.
   Tailwind colors as hex for browsers without oklch support (Chrome < 111, Safari < 15.4,
   Firefox < 113). Modern browsers skip this block entirely. */
@supports not (color: oklch(0% 0 0)) {
  :root, :host {
${lines.join("\n")}
  }
}
`);
console.log(`wrote ${lines.length} colors`);
